#![allow(clippy::expect_used, clippy::panic)] // Build scripts report failure via panic/expect; that is cargo's normal build-error path.
//! Scans `src/modules/*/mod.rs` and generates the module table.
//!
//! Rerun conditions point at the directory itself (so adding or removing a
//! module directory retriggers the scan) plus every known `mod.rs` (so edits
//! retrigger even on a Cargo that watches directories shallowly).

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// Whether `name` is usable as a Rust module name.
fn is_module_name(name: &str) -> bool {
    let mut chars = name.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// Sorted module directory names holding a `mod.rs` file.
fn discover(modules_dir: &Path) -> Vec<String> {
    let mut names = Vec::new();
    match fs::read_dir(modules_dir) {
        Ok(entries) => {
            for entry in entries.flatten() {
                let name = entry.file_name().to_string_lossy().into_owned();
                if entry.path().join("mod.rs").is_file() && is_module_name(&name) {
                    names.push(name);
                }
            }
        }
        Err(err) => panic!("A3: cannot read {}: {err}", modules_dir.display()),
    }
    names.sort();
    names
}

/// Escapes `path` for embedding in a double-quoted `#[path]` attribute.
fn escape_for_path_attr(path: &Path) -> String {
    path.display()
        .to_string()
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
}

fn main() {
    println!("cargo:rerun-if-changed=src/modules");
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("Cargo sets this"));
    let modules_dir = manifest_dir.join("src/modules");
    let names = discover(&modules_dir);
    let mut out =
        String::from("// @generated by build.rs from src/modules/*/mod.rs; do not edit.\n");
    for name in &names {
        let file = escape_for_path_attr(&modules_dir.join(name).join("mod.rs"));
        let _ = writeln!(
            out,
            "/// Auto-discovered module `{name}`.\n#[path = \"{file}\"]\npub mod {name};"
        );
    }
    out.push_str("/// Auto-discovered descriptors of this domain crate, sorted by module id.\n");
    out.push_str("pub static MODULES: &[&::lightamer_iop_traits::ModuleDesc] = &[");
    for name in &names {
        let _ = write!(out, "&{name}::DESC,");
    }
    out.push_str("];\n");
    let gen_file =
        PathBuf::from(env::var("OUT_DIR").expect("Cargo sets this")).join("modules_gen.rs");
    fs::write(&gen_file, out).expect("cannot write modules_gen.rs");
    for name in &names {
        println!("cargo:rerun-if-changed=src/modules/{name}/mod.rs");
    }
}
