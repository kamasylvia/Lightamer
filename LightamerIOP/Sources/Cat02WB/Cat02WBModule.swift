// ─────────────────────────────────────────────────────────────────────────
// Cat02WBModule (Plan M2-5-1 T3; KD-4) — the Alcedo `cat02_white_balance`
// catalog op: creative CAT02 white balance applied in the ACEScc grade
// domain. The envelope decodes ACEScc → linear AP1 around this op, so the
// kernel's job is: decode → 3×3 CAT02 adaptation → re-encode (the exact
// Alcedo behavior-0 shape, primary_grade.metal/adjustment_runtime.cpp).
//
// The adaptation rides FROM the illuminant named by (temperature, tint) TO
// the ACES white (0.32168, 0.33767) in the AP1(D60) basis:
//   M = XYZ_D60→AP1 · CAT02⁻¹ · diag(dstLMS/srcLMS) · CAT02 · AP1→XYZ_D60
// (Alcedo BuildAp1Cat02WhiteBalanceMatrix, develop_color_transform.cpp).
// The illuminant xy comes from the RAW Custom WB CCT/tint scale: the
// Planckian locus uv at CCT (Planck's law against the CIE 1931 2° CMF,
// c2 = 1.4387774e-2 — the same generation inputs as the Alcedo locus
// table, computed here by direct integration so no table data is copied)
// offset along the locus normal by −tint/3000.
//
// Identity (KD-4): (5999.9934 K, 9.7112783) solves to the ACES white xy
// (machine-checked ≤1e-4; actual ~2e-7), so the default commits an
// EARLY-EXIT flag (Alcedo packs values[0] = 0 the same way) and the
// kernel is a byte-identical copy — identity at pixel tolerance 0.
//
// Camera WB stays on the RAW Decode / CIRAW layer (M2GRADE-04); this op is
// the Look-page creative color temperature.
// ─────────────────────────────────────────────────────────────────────────

public enum Cat02WBKernel {
    /// MSL function name (`Cat02WB.metal`).
    public static let functionName = "grade_cat02_wb"
    public static let metalBundle = Bundle(for: IOPBundleMarker.self)
}

public final class Cat02WBModule: IOPModule {

    /// Alcedo Cat02WhiteBalancePayload tunable face (the `enabled` field is
    /// the Lightamer ModuleInstance.enabled flag here, not a param).
    public struct Params: Codable, Hashable, Sendable {
        /// Illuminant CCT in Kelvin (2000–15000); the AP1-white default is
        /// identity (KD-4).
        public var temperature: Float
        /// Illuminant tint on the RAW Custom WB tint scale (±150).
        public var tint: Float

        public init(temperature: Float = 5999.9934, tint: Float = 9.7112783) {
            self.temperature = temperature
            self.tint = tint
        }
    }

    /// The identity pair (KD-4) — also the Alcedo header constants.
    public static let identityTemperature: Float = 5999.9934
    public static let identityTint: Float = 9.7112783

    /// Alcedo kCat02TemperatureMin/Max, kCat02TintMin/Max.
    public static let temperatureRange: ClosedRange<Float> = (2000.0...15000.0)
    public static let tintRange: ClosedRange<Float> = (-150.0...150.0)

    public static let opName = "cat02WhiteBalance"

    /// LIGHTAMER V50Order row 41.4 (colorequal 41.2 之后).
    public static let iopOrder: Float = 41.4

    public static let flags: IOPFlags = [.supportsBlending, .allowTiling]
    public static let defaultColorspace: IOPColorspace = .RGB

    /// Alcedo ApplyUpdate clamp (finite → min/max).
    public static func clamped(_ params: Params) -> Params {
        Params(
            temperature: min(
                max(params.temperature, temperatureRange.lowerBound), temperatureRange.upperBound),
            tint: min(max(params.tint, tintRange.lowerBound), tintRange.upperBound))
    }

    /// The kernel early-exit predicate (Alcedo's `values[0] = 0` packing):
    /// the default pair IS the AP1 white — the adaptation matrix would be
    /// the identity to ~7e-7, and the packed branch skips it entirely so
    /// the identity pixel tolerance is 0.
    public static func isIdentity(_ params: Params) -> Bool {
        params.temperature == identityTemperature && params.tint == identityTint
    }

    private let device: (any MTLDevice)?
    private var uniformsBuffer: (any MTLBuffer)?
    private var committedFlag: Float = -1

    public init(device: (any MTLDevice)? = nil) {
        self.device = device
    }

    public func reloadDefaults(image: DecodedImage) async -> Params {
        Params()
    }

    public func commitParams(_ params: Params, into piece: inout IOPiece) {
        piece.paramsHash = StableHash.hash(ParamsCoding.encode(params))
        let clamped = Self.clamped(params)
        // Uniforms: [flag, row0(3), row1(3), row2(3), pad] — 16 floats.
        // flag 0 = the identity early exit (byte-identical copy); flag 1 =
        // apply the row-major adaptation in linear AP1.
        var floats = [Float](repeating: 0, count: 16)
        if Self.isIdentity(clamped) {
            floats[0] = 0
        } else {
            floats[0] = 1
            let rows = Cat02WBMath.adaptationRows(
                temperature: Double(clamped.temperature), tint: Double(clamped.tint))
            for (index, value) in rows.enumerated() {
                floats[1 + index] = Float(value)
            }
        }
        if uniformsBuffer == nil || committedFlag != floats[0] {
            let resolved = device ?? MTLCreateSystemDefaultDevice()
            uniformsBuffer = resolved?.makeBuffer(
                length: 16 * MemoryLayout<Float>.stride, options: .storageModeShared)
            committedFlag = floats[0]
        }
        guard let buffer = uniformsBuffer else {
            piece.data = nil
            return
        }
        floats.withUnsafeBytes {
            buffer.contents().copyMemory(
                from: $0.baseAddress!, byteCount: 16 * MemoryLayout<Float>.stride)
        }
        piece.data = buffer
    }

    public func process(
        input: any MTLTexture,
        output: any MTLTexture,
        roiIn: ROI,
        roiOut: ROI,
        piece: inout IOPiece,
        metal: MetalContext
    ) async throws {
        guard let buffer = piece.data else { return }
        try await metal.dispatch2DTexture(
            functionName: Cat02WBKernel.functionName,
            input: input,
            output: output
        ) { encoder in
            encoder.setBuffer(buffer, offset: 0, index: 0)
        }
    }

    // MARK: - CPU reference (KD-8 — the golden test's Float64 mirror)

    /// The Float64 reference: ACEScc decode → adaptation → encode. The
    /// same derivation the kernel and the uniforms ride; golden tests pin
    /// kernel vs this at the KD-8 tolerances.
    public static func reference(
        acescc: SIMD3<Double>, temperature: Double, tint: Double
    ) -> SIMD3<Double> {
        if isIdentity(Params(
            temperature: Float(temperature), tint: Float(tint)))
        {
            return acescc
        }
        let linear = SIMD3(
            Cat02WBMath.acesccDecode(acescc.x),
            Cat02WBMath.acesccDecode(acescc.y),
            Cat02WBMath.acesccDecode(acescc.z))
        let rows = Cat02WBMath.adaptationRows(temperature: temperature, tint: tint)
        let adapted = SIMD3(
            rows[0] * linear.x + rows[1] * linear.y + rows[2] * linear.z,
            rows[3] * linear.x + rows[4] * linear.y + rows[5] * linear.z,
            rows[6] * linear.x + rows[7] * linear.y + rows[8] * linear.z)
        return SIMD3(
            Cat02WBMath.acesccEncode(adapted.x),
            Cat02WBMath.acesccEncode(adapted.y),
            Cat02WBMath.acesccEncode(adapted.z))
    }
}

