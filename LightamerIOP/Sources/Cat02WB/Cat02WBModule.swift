    /// Blackbody chromaticity in CIE 1960 uv at `cct` (Planck's law × CMF,
    /// trapezoid over 1 nm; normalization cancels in the chromaticity).
    public static func planckianUV(_ cct: Double) -> SIMD2<Double> {
        var X = 0.0, Y = 0.0, Z = 0.0
        let nm0 = 360.0
        for index in 0..<cie1931CMF.count {
            let lambdaNm = nm0 + Double(index)
            let lambdaM = lambdaNm * 1e-9
            let power =
                (1.0 / (lambdaM * lambdaM * lambdaM * lambdaM * lambdaM))
                / (exp(planckC2 / (lambdaM * cct)) - 1.0)
            // Trapezoid weights: 0.5 at both ends, 1.0 inside (1 nm step).
            let weight =
                (index == 0 || index == cie1931CMF.count - 1)
                ? 0.5 * power : power
            X += weight * cie1931CMF[index].0
            Y += weight * cie1931CMF[index].1
            Z += weight * cie1931CMF[index].2
        }
        // The 1 nm step factor cancels in the chromaticity ratio below.
        let denominator = X + 15.0 * Y + 3.0 * Z
        return SIMD2(4.0 * X / denominator, 6.0 * Y / denominator)
    }

    /// The locus normal at `cct` (Alcedo PlanckianLocusAtCCT: the tangent
    /// over a ±deltaK window, rotated 90° and normalized).
    public static func locusPerp(_ cct: Double) -> SIMD2<Double> {
        let safe = min(max(cct, cctRange.lowerBound), cctRange.upperBound)
        let deltaK = min(
            max(safe * 0.001, 0.5), max(0.5, 0.25 * (cctRange.upperBound - cctRange.lowerBound)))
        let low = max(cctRange.lowerBound, safe - deltaK)
        let high = min(cctRange.upperBound, safe + deltaK)
        let uv = planckianUV(safe)
        let tangent = (planckianUV(high) - planckianUV(low)) / (high - low)
        let length = sqrt(tangent.x * tangent.x + tangent.y * tangent.y)
        guard length > 1e-10 else { return SIMD2(0, 0) }
        return SIMD2(-tangent.y / length, tangent.x / length)
    }

    /// The RAW Custom WB CCT/tint scale → chromaticity (Alcedo
    /// TemperatureTintToUV → UVToXY).
    public static func temperatureTintToXY(temperature: Double, tint: Double) -> SIMD2<Double> {
        let perp = locusPerp(temperature)
        let duv = min(max(tint, tintRange.lowerBound), tintRange.upperBound) / tintScale
        let uv = planckianUV(temperature)
        let u = uv.x - perp.x * duv
        let v = uv.y - perp.y * duv
        let denominator = u - 4.0 * v + 2.0
        return SIMD2(1.5 * u / denominator, v / denominator)
    }

    public static func xyToXYZ(_ xy: SIMD2<Double>) -> SIMD3<Double> {
        let y = max(xy.y, 1e-10)
        return SIMD3(xy.x / y, 1.0, (1.0 - xy.x - xy.y) / y)
    }

    /// The row-major AP1-basis CAT02 adaptation (Alcedo
    /// BuildAp1Cat02WhiteBalanceMatrix) — 9 doubles for the uniforms/test
    /// reference.
    public static func adaptationRows(temperature: Double, tint: Double) -> [Double] {
        let sourceLMS = apply(cat02, xyToXYZ(temperatureTintToXY(temperature: temperature, tint: tint)))
        let destinationLMS = apply(cat02, xyToXYZ(acesWhiteXY))
        let gain = [
            destinationLMS.x / max(sourceLMS.x, 1e-10), 0, 0,
            0, destinationLMS.y / max(sourceLMS.y, 1e-10), 0,
            0, 0, destinationLMS.z / max(sourceLMS.z, 1e-10),
        ]
        func mul(_ a: [Double], _ b: [Double]) -> [Double] {
            var result = [Double](repeating: 0, count: 9)
            for row in 0..<3 {
                for column in 0..<3 {
                    var sum = 0.0
                    for k in 0..<3 {
                        sum += a[row * 3 + k] * b[k * 3 + column]
                    }
                    result[row * 3 + column] = sum
                }
            }
            return result
        }
        // XYZ_D60→AP1 · CAT02⁻¹ · gain · CAT02 · AP1→XYZ_D60
        return mul(
            mul(xyzD60ToAP1, mul(cat02Inverse, gain)),
            mul(cat02, ap1ToXYZD60))
    }
