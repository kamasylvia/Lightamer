        SIMD3(
            m[0] * v.x + m[1] * v.y + m[2] * v.z,
            m[3] * v.x + m[4] * v.y + m[5] * v.z,
            m[6] * v.x + m[7] * v.y + m[8] * v.z)
    }

    // MARK: ACEScc (the Swift mirror of ACESccMath.metal — KD-8 reference)
    //
    // The constants are the SHIPPED float32 values promoted to Double
    // (`Double(Float(17.52))` etc.) — the golden gate measures FORMULA
    // fidelity, not constant-literal rounding: the kernel inevitably runs
    // f32(17.52) = 17.5199985504..., and an exact-decimal reference would
    // bake a ~4e-5 decode-slope skew into every linear-leg sample (the
    // KD-2 "Float64 推导后降 float32 常数" clause, applied to the math
    // constants too — signed in M2-5-1-DECISIONS).

    static let kA = Double(Float(9.72))
    static let kB = Double(Float(17.52))
    static let kOffset = Double(Float(0.0000152587890625))
    static let kTransition = Double(Float(0.000030517578125))

    public static func acesccEncode(_ value: Double) -> Double {
        let kFloor = (-16.0 + kA) / kB
        if value < 0 { return kFloor + value }
        if value < kTransition { return (log2(kOffset + value * 0.5) + kA) / kB }
        return (log2(value) + kA) / kB
    }

    public static func acesccDecode(_ value: Double) -> Double {
        let kFloor = (-16.0 + kA) / kB
        let kThreshold = (-15.0 + kA) / kB
        if value < kFloor { return value - kFloor }
        if value <= kThreshold { return (exp2(value * kB - kA) - kOffset) * 2.0 }
        return exp2(value * kB - kA)
    }

